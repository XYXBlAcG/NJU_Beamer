use crate::{
    archive::{self, ArchiveEntry},
    document::{self, DocumentAsset},
};
use std::{collections::BTreeMap, fs, path::Path};

pub fn write(
    path: &Path,
    source: &str,
    assets: &[DocumentAsset],
    template: &Path,
    paper: bool,
) -> Result<(), String> {
    let mut resources = BTreeMap::new();
    let mut pictures = BTreeMap::new();
    if !paper {
        resources.insert(
            "NJU.sty".to_owned(),
            fs::read(template.join("NJU.sty")).map_err(|error| error.to_string())?,
        );
        pictures.insert(
            "pic/NJU_Logo.png".to_owned(),
            fs::read(template.join("pic/NJU_Logo.png")).map_err(|error| error.to_string())?,
        );
    }
    for asset in assets {
        document::validate_asset(asset)?;
        pictures.insert(asset.path.clone(), asset.content.clone());
    }
    if paper {
        resources.extend(
            fs::read_dir(template.join("paper"))
                .map_err(|error| error.to_string())?
                .map(|entry| {
                    let entry = entry.map_err(|error| error.to_string())?;
                    Ok((
                        entry.file_name().to_string_lossy().into_owned(),
                        fs::read(entry.path()).map_err(|error| error.to_string())?,
                    ))
                })
                .collect::<Result<BTreeMap<String, Vec<u8>>, String>>()?,
        );
    }
    let mut entries = vec![
        ArchiveEntry {
            path: if paper { "paper.tex" } else { "slide.tex" },
            content: Some(source.as_bytes()),
        },
        ArchiveEntry {
            path: "pic/",
            content: None,
        },
    ];
    entries.extend(pictures.iter().map(|(path, content)| ArchiveEntry {
        path,
        content: Some(content),
    }));
    entries.extend(resources.iter().map(|(path, content)| ArchiveEntry {
        path,
        content: Some(content),
    }));
    archive::write(path, &entries)
}

#[cfg(test)]
mod tests {
    use super::*;
    use std::io::Read;

    #[test]
    fn exports_compilable_bundle_structure() {
        let directory = tempfile::tempdir().unwrap();
        let output = directory.path().join("slides.zip");
        let template = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../templates/nju");
        write(&output, "\\documentclass{beamer}", &[], &template, false).unwrap();
        let mut zip = zip::ZipArchive::new(fs::File::open(output).unwrap()).unwrap();
        for name in ["slide.tex", "NJU.sty", "pic/NJU_Logo.png"] {
            let mut entry = zip.by_name(name).unwrap();
            let mut bytes = Vec::new();
            entry.read_to_end(&mut bytes).unwrap();
            assert!(!bytes.is_empty());
        }
    }

    #[test]
    fn exports_paper_class_and_cover_resources() {
        let directory = tempfile::tempdir().unwrap();
        let output = directory.path().join("paper.zip");
        let template = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../templates/nju");
        write(&output, "\\documentclass{njuthesis}", &[], &template, true).unwrap();
        let mut zip = zip::ZipArchive::new(fs::File::open(output).unwrap()).unwrap();
        for name in [
            "paper.tex",
            "njuthesis.cls",
            "njuthesis-undergraduate.def",
            "njuthesis-graduate.def",
            "nju-emblem-purple.pdf",
            "LICENSE",
        ] {
            assert!(zip.by_name(name).unwrap().size() > 0);
        }
        assert!(zip.by_name("slide.tex").is_err());
        assert!(zip.by_name("NJU.sty").is_err());
    }

    #[test]
    #[ignore = "Requires the four documents generated by verify:papers and MacTeX"]
    fn compiles_exported_papers_without_template_search_paths() {
        let root = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../.tmp/papers");
        let template = Path::new(env!("CARGO_MANIFEST_DIR")).join("../../templates/nju");
        for kind in ["bachelor", "master", "doctor", "report"] {
            let directory = tempfile::tempdir().unwrap();
            let source = fs::read_to_string(root.join(kind).join("paper.tex")).unwrap();
            let image = DocumentAsset {
                path: "pic/commutative.png".into(),
                mime_type: "image/png".into(),
                content: fs::read(root.join(kind).join("pic/commutative.png")).unwrap(),
            };
            let output = directory.path().join("paper.zip");
            write(&output, &source, &[image], &template, true).unwrap();
            let mut zip = zip::ZipArchive::new(fs::File::open(output).unwrap()).unwrap();
            zip.extract(directory.path()).unwrap();
            let result = std::process::Command::new("/Library/TeX/texbin/latexmk")
                .args([
                    "-xelatex",
                    "-interaction=nonstopmode",
                    "-halt-on-error",
                    "-latexoption=-no-shell-escape",
                    "paper.tex",
                ])
                .env(
                    "PATH",
                    format!(
                        "/Library/TeX/texbin:{}",
                        std::env::var("PATH").unwrap_or_default()
                    ),
                )
                .env_remove("TEXINPUTS")
                .current_dir(directory.path())
                .output()
                .unwrap();
            assert!(
                result.status.success(),
                "{kind}: {}",
                String::from_utf8_lossy(&result.stdout)
            );
            assert!(fs::read(directory.path().join("paper.pdf"))
                .unwrap()
                .starts_with(b"%PDF-"));
        }
    }
}
